def add_months(dt: datetime, months: int) -> datetime:































    month_index = dt.month - 1 + months































    year = dt.year + month_index // 12































    month = month_index % 12 + 1































































    day = min(































        dt.day,































        calendar.monthrange(year, month)[1],































    )































































    return dt.replace(































        year=year,































        month=month,































        day=day,































    )































































































def get_expiry(plan: str, activated_at: datetime) -> datetime:































    if plan == "Monthly":































        return add_months(activated_at, 1)































































    if plan == "Yearly":































        return add_months(activated_at, 12)































































    # Lifetime = 5 years under the current Chatly implementation.































    return add_months(activated_at, 60)































































































