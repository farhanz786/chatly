def _mark_expired_sheet_rows_sync(now):







    spreadsheet, worksheet = _setup_purchase_sheet_sync()







    values = worksheet.get_all_values()















    if len(values) <= 1:







        return















    from datetime import timezone as _timezone







    updates = []















    for row_number, row in enumerate(values[1:], start=2):







        if len(row) < 8 or row[7] != "Active":







            continue















        try:







            expires_text = row[6].strip()







            expires_at = datetime.strptime(







                expires_text,







                "%d %b %Y, %I:%M %p IST",







            ).replace(
                tzinfo=timezone(timedelta(hours=5, minutes=30), "IST")
            ).astimezone(timezone.utc)







        except (ValueError, TypeError):







            continue















        if expires_at <= now:







            updates.append({







                "range": f"H{row_number}",







                "values": [["Expired"]],







            })















    if updates:







        worksheet.batch_update(updates, value_input_option="USER_ENTERED")























