    def _is_successful_bump_message(self, message: discord.Message):
        if message.channel.id != BUMP_CHANNEL_ID:
            return False
        if message.author.id != DISBOARD_BOT_ID:
            return False
        parts = [message.content or ""]
        for embed in message.embeds:
            parts.extend([embed.title or "", embed.description or ""])
            parts.extend(field.value or "" for field in embed.fields)
        text = " ".join(parts).lower()
        return "bump done" in text or "bump successful" in text

    @commands.Cog.listener()
    async def on_message(self, message: discord.Message):
        if message.author.bot and self._is_successful_bump_message(message):
            guild = message.guild
            if guild is None:
                return
            data = _load_bump_reminders()
            data[str(guild.id)] = {
                "guild_id": guild.id,
                "channel_id": BUMP_CHANNEL_ID,
                "bumped_by": message.author.id,
                "successful_bump_message_id": message.id,
                "bumped_at": datetime.now(timezone.utc).isoformat(),
                "remind_at": (datetime.now(timezone.utc) + timedelta(seconds=BUMP_COOLDOWN_SECONDS)).isoformat(),
                "reminder_sent": False,
            }
            _save_bump_reminders(data)

    @tasks.loop(minutes=1)
    async def check_bump_reminders(self):
        data = _load_bump_reminders()
        changed = False
        now = datetime.now(timezone.utc)
        for guild_id, record in list(data.items()):
            if record.get("reminder_sent"):
                continue
            try:
                remind_at = datetime.fromisoformat(record["remind_at"])
            except (KeyError, ValueError, TypeError):
                record["reminder_sent"] = True
                changed = True
                continue
            if now < remind_at:
                continue
            guild = self.bot.get_guild(int(guild_id))
            if guild is None:
                continue
            channel = guild.get_channel(BUMP_CHANNEL_ID)
            if channel is None:
                try:
                    channel = await self.bot.fetch_channel(BUMP_CHANNEL_ID)
                except (discord.NotFound, discord.Forbidden, discord.HTTPException):
                    continue
            role = guild.get_role(BUMP_REMINDER_ROLE_ID)
            mention = role.mention if role is not None else ""
            embed = discord.Embed(
                title="<:boost:1550552457120190585> It’s Time to Bump Chatly!",
                description=(
                    f"<:boost:1550552457120190585> The 2-hour bump cooldown has ended.\n\n"
                    f"Use **/bump** in <#{BUMP_CHANNEL_ID}> to bump Chatly again.\n\n"
                    f"<:chatly_coins:1550907460959866991> **Earn 10,000 Chatly Coins** for a successful bump."
                ),
                color=0x8A2BE2,
            )
            embed.set_image(url=BUMP_REMINDER_IMAGE_URL)
            try:
                await channel.send(content=mention or None, embed=embed, view=BumpReminderView(), allowed_mentions=discord.AllowedMentions(roles=True))
            except discord.HTTPException as exc:
                print(f"Bump reminder send failed: {exc}")
                continue
            record["reminder_sent"] = True
            changed = True
        if changed:
            _save_bump_reminders(data)

