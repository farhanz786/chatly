def _load_bump_reminders():
    try:
        if not BUMP_REMINDER_FILE.exists():
            return {}
        with BUMP_REMINDER_FILE.open("r", encoding="utf-8") as file:
            data = json.load(file)
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def _save_bump_reminders(data):
    try:
        with BUMP_REMINDER_FILE.open("w", encoding="utf-8") as file:
            json.dump(data, file, indent=2)
    except OSError as exc:
        print(f"Bump reminder data save failed: {exc}")


async def toggle_bump_notifications(interaction: discord.Interaction):
    role = interaction.guild.get_role(BUMP_REMINDER_ROLE_ID) if interaction.guild else None
    if role is None:
        await interaction.response.send_message(
            "<:info:1550551426269319168> The bump reminder role could not be found.",
            ephemeral=True,
        )
        return

    try:
        if role in interaction.user.roles:
            await interaction.user.remove_roles(role, reason="Disabled Chatly bump reminders")
            message = "Bump reminder role removed."
        else:
            await interaction.user.add_roles(role, reason="Enabled Chatly bump reminders")
            message = "Bump reminder role added."
    except discord.Forbidden:
        message = "<:info:1550551426269319168> I don't have permission to manage the bump reminder role."
    except discord.HTTPException:
        message = "<:info:1550551426269319168> Discord rejected the role update. Please try again."

    await interaction.response.send_message(message, ephemeral=True)


