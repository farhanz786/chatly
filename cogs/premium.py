def _delete_purchase_sheet_row_sync(
    member_name,
    member_id,
    plan,
    amount,
    activated_at,
    expires_at,
    sheet_row=None,
):
    spreadsheet, worksheet = _setup_purchase_sheet_sync()
    values = worksheet.get_all_values()

    row_number = None
    if sheet_row and 2 <= int(sheet_row) <= len(values):
        row_number = int(sheet_row)
    else:
        ist = timezone(timedelta(hours=5, minutes=30), "IST")
        activated_text = activated_at.astimezone(ist).strftime(
            "%d %b %Y, %I:%M %p IST"
        )
        expires_text = expires_at.astimezone(ist).strftime(
            "%d %b %Y, %I:%M %p IST"
        )
        target = [member_name, str(member_id), "Premium", plan, amount, activated_text, expires_text]
        for number, row in enumerate(values[1:], start=2):
            if row[:7] == target:
                row_number = number

    if row_number is None:
        return False

    worksheet.delete_rows(row_number)
    return True


def _find_active_purchase_sheet_record_sync(member_name, member_id):
    spreadsheet, worksheet = _setup_purchase_sheet_sync()
